// Код кімнати — 4 латинські літери. Гравці часто набирають його з українською (або російською) розкладкою:
// тоді кожну кириличну літеру перекладаємо на латинську за тією самою клавішею (ЯОІА → ZJSF), а решту символів відкидаємо.
const LAYOUT: Record<string, string> = {
  Й: "Q", Ц: "W", У: "E", К: "R", Е: "T", Н: "Y", Г: "U", Ш: "I", Щ: "O", З: "P",
  Ф: "A", І: "S", Ы: "S", В: "D", А: "F", П: "G", Р: "H", О: "J", Л: "K", Д: "L",
  Я: "Z", Ч: "X", С: "C", М: "V", И: "B", Т: "N", Ь: "M",
};

export function normalizeRoomCode(raw: string): string {
  return [...raw.toUpperCase()]
    .map((ch) => LAYOUT[ch] ?? ch)
    .filter((ch) => ch >= "A" && ch <= "Z")
    .join("")
    .slice(0, 4);
}
